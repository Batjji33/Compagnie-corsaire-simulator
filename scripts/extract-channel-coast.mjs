// Reproducible offline extraction from Natural Earth 1:10m land (public domain).
// Download ne_10m_land.geojson to .qa/ne-land.geojson before running this script.
import fs from 'node:fs';
const source=JSON.parse(fs.readFileSync('.qa/ne-land.geojson','utf8'));
function clip(points,box){
 let out=points;
 for(const [axis,bound,sign] of [[0,box[0],1],[0,box[2],-1],[1,box[1],1],[1,box[3],-1]]){
  const input=out;out=[];if(!input.length)break;
  for(let i=0;i<input.length;i++){const a=input[i],b=input[(i+1)%input.length],ia=(a[axis]-bound)*sign>=0,ib=(b[axis]-bound)*sign>=0;
   if(ia)out.push(a);if(ia!==ib){const t=(bound-a[axis])/(b[axis]-a[axis]);out.push([a[0]+t*(b[0]-a[0]),a[1]+t*(b[1]-a[1])]);}
  }
 }return out;
}
const rings=[];
for(const feature of source.features)for(const polygon of feature.geometry.type==='MultiPolygon'?feature.geometry.coordinates:[feature.geometry.coordinates]){
 const ring=polygon[0];const minX=Math.min(...ring.map(p=>p[0])),maxX=Math.max(...ring.map(p=>p[0])),minY=Math.min(...ring.map(p=>p[1])),maxY=Math.max(...ring.map(p=>p[1]));
 if(maxX<-3||minX>-.5||maxY<48.73||minY>51)continue;
 // Replace only the British mainland's Portsmouth area with harbour-scale authored coastlines.
 const boxes=maxY>51&&minY>49?[[-3,48.73,-.5,50.70],[-3,50.90,-.5,51],[-3,50.70,-1.3,50.90],[-.95,50.70,-.5,50.90]]:[[minY<49?-1.95:-3,48.73,-.5,51]];
 for(const box of boxes){const c=clip(ring,box);if(c.length<3)continue;const rounded=c.map(p=>p.map(v=>+v.toFixed(5)));rings.push(rounded);}
}
fs.writeFileSync('src/world/channelCoast.ts',`/** Natural Earth 1:10m land, public domain. Generated by scripts/extract-channel-coast.mjs.\n * Regional silhouettes only; harbour geometry is maintained separately. [longitude, latitude]. */\nexport const REGIONAL_COAST: readonly (readonly (readonly [number,number])[])[] = ${JSON.stringify(rings)};\n`);
console.log({rings:rings.length,vertices:rings.reduce((s,r)=>s+r.length,0)});
